export const HTML_LANG: Record<Lang, string> = { en: 'en', hi: 'hi', gu: 'gu' }

export function flatten(tree: unknown, prefix = ''): Record<string, string> {
  if (typeof tree === 'string') return prefix ? { [prefix]: tree } : {}
  if (!tree || typeof tree !== 'object') return {}
  return Object.entries(tree).reduce<Record<string, string>>((all, [key, value]) => {
    const next = prefix ? `${prefix}.${key}` : key
    return { ...all, ...flatten(value, next) }
  }, {})
}

export function translate(lang: Lang, path: string, simple = false, vars?: Record<string, string | number>): string {
  const short = simple ? SIMPLE[lang][path] : undefined
  const template = short ?? flatten(MESSAGES[lang])[path] ?? flatten(MESSAGES.en)[path] ?? path
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''))
}

export function categoryKey(category: CpcbCategoryId): string {
  if (category === 'very-poor') return 'cat.veryPoor'
  return `cat.${category}`
}
